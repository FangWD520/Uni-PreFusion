import argparse
import json
from collections import defaultdict


def load_report(path):
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)


def group_counts(keys, prefixes):
    out = defaultdict(int)
    for k in keys:
        hit = False
        for name, prefix in prefixes:
            if k.startswith(prefix):
                out[name] += 1
                hit = True
                break
        if not hit:
            out['other'] += 1
    return dict(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('report', help='*.report.json generated by merge_mambafusion_unilion_ckpts.py')
    parser.add_argument('--strict-mm', action='store_true', help='fail if any current mm_frontend.mm_backbone tensor is random')
    args = parser.parse_args()

    r = load_report(args.report)
    mf_loaded_dst = [dst for _, dst in r['mambafusion_loaded']]
    uni_loaded = r['unilion_loaded']
    random_keys = r['still_random_init']
    mf_mismatch = r['mambafusion_shape_mismatch']
    uni_mismatch = r['unilion_shape_mismatch']

    groups = [
        ('mf_mm_backbone', 'mm_frontend.mm_backbone.'),
        ('mf_ext_vmamba', 'mm_frontend.mf_img_backbone.'),
        ('mf_img_neck', 'mm_frontend.mf_img_neck.'),
        ('learned_pillar_adapter', 'mm_frontend.z_embed'),
        ('learned_pillar_adapter', 'mm_frontend.pillar_value.'),
        ('learned_pillar_adapter', 'mm_frontend.pillar_score.'),
        ('unilion_vfe', 'pts_voxel_encoder.'),
        ('unilion_lion3d', 'pts_backbone.'),
        ('unilion_lss', 'img_map2bev.'),
        ('unilion_map2bev', 'map2bev.'),
        ('unilion_bev_backbone', 'bev_backbone.'),
        ('unilion_pts_neck', 'pts_neck.'),
        ('unilion_det_head', 'det_head.'),
        ('unilion_map_head', 'map_head.'),
        ('unilion_occ_head', 'occ_head.'),
        ('unilion_motion_head', 'motion_head.'),
        ('unilion_planning_head', 'planning_head.'),
    ]

    summary = {
        'model_params': r.get('model_params'),
        'unilion_loaded_total': len(uni_loaded),
        'mambafusion_loaded_total': len(mf_loaded_dst),
        'random_total': len(random_keys),
        'unilion_loaded_by_group': group_counts(uni_loaded, groups),
        'mambafusion_loaded_by_group': group_counts(mf_loaded_dst, groups),
        'random_by_group': group_counts(random_keys, groups),
    }

    mm_random = [k for k in random_keys if k.startswith('mm_frontend.mm_backbone.')]
    mm_mismatch = [x for x in mf_mismatch if x[1].startswith('mm_frontend.mm_backbone.')]
    vmamba_random = [k for k in random_keys if k.startswith('mm_frontend.mf_img_backbone.')]
    neck_random = [k for k in random_keys if k.startswith('mm_frontend.mf_img_neck.')]
    adapter_random = [k for k in random_keys if k.startswith(('mm_frontend.z_embed', 'mm_frontend.pillar_value.', 'mm_frontend.pillar_score.'))]

    print(json.dumps(summary, indent=2))
    print('\nCritical checks:')
    print('  current mm_frontend.mm_backbone random:', len(mm_random))
    print('  current mm_frontend.mm_backbone mf shape-mismatch/missing:', len(mm_mismatch))
    print('  external VMamba random:', len(vmamba_random))
    print('  image neck random:', len(neck_random))
    print('  expected-new learned adapter random:', len(adapter_random))

    if mm_random:
        print('\n[WARN] Random mm_backbone tensors sample:')
        for k in mm_random[:50]:
            print(' ', k)
    if mm_mismatch:
        print('\n[WARN] MambaFusion mm_backbone mismatches/missing sample:')
        for x in mm_mismatch[:50]:
            print(' ', x)
    if neck_random:
        print('\n[INFO] Random image neck tensors sample:')
        for k in neck_random[:30]:
            print(' ', k)
    if adapter_random:
        print('\n[INFO] Expected random learned adapter tensors sample:')
        for k in adapter_random[:30]:
            print(' ', k)

    if args.strict_mm and (mm_random or mm_mismatch):
        raise SystemExit('Strict MambaFusion mm_backbone coverage check failed')


if __name__ == '__main__':
    main()
